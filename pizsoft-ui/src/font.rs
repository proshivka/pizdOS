// Modern smooth anti-aliased vector sans-serif UI font (Inter-inspired).
// Supports printable ASCII (0x20..=0x7E), Russian Cyrillic (А-Я, а-я, Ё, ё),
// and UI symbols. Zero external font files, zero external dependencies.

use std::cell::RefCell;
use std::collections::HashMap;

pub const GLYPH_H: usize = 14;

#[derive(Clone, Copy)]
pub enum Seg {
    /// Line segment (x0, y0, x1, y1) in 0..100 vertical units
    L(i16, i16, i16, i16),
    /// Quadratic Bezier (x0, y0, cx, cy, x1, y1)
    Q(i16, i16, i16, i16, i16, i16),
    /// Elliptical arc (cx, cy, rx, ry, start_deg, end_deg), 0=right, 90=down
    E(i16, i16, i16, i16, i16, i16),
    /// Solid circle dot (cx, cy, radius_units)
    D(i16, i16, i16),
}

pub struct VectorGlyph {
    pub advance: i16,
    pub segs: &'static [Seg],
}

pub struct RasterGlyph {
    pub advance: i32,
    pub advance_f: f32,
    pub width: usize,
    pub height: usize,
    pub alpha: Vec<u8>,
}

struct FontCaches {
    ascii_1x: [Option<&'static RasterGlyph>; 95],
    other: HashMap<(char, i32, u16), &'static RasterGlyph>,
}

impl FontCaches {
    fn new() -> Self {
        Self {
            ascii_1x: [None; 95],
            other: HashMap::with_capacity(256),
        }
    }
}

thread_local! {
    static GLYPH_CACHE: RefCell<FontCaches> = RefCell::new(FontCaches::new());
}

#[inline]
pub fn px_height_for_scale(scale: i32) -> i32 {
    if scale <= 1 {
        14
    } else {
        12 * scale + 2
    }
}

#[inline]
fn ui_scale_key(ui_scale: f32) -> u16 {
    (ui_scale.clamp(0.5, 4.0) * 100.0).round() as u16
}

pub fn measure_text_scaled(s: &str, scale: i32, ui_scale: f32) -> i32 {
    let sc = scale.max(1);
    let ui = ui_scale.clamp(0.5, 4.0);
    let mut total_f = 0.0f32;
    for ch in s.chars() {
        total_f += rasterize_scaled_cached(ch, sc, ui).advance_f;
    }
    (total_f / ui).ceil() as i32
}

pub fn rasterize_scaled_cached(ch: char, scale: i32, ui_scale: f32) -> &'static RasterGlyph {
    let s = scale.max(1);
    let key_s = ui_scale_key(ui_scale);
    GLYPH_CACHE.with(|cache| {
        let mut fc = cache.borrow_mut();
        if s == 1 && key_s == 100 {
            let u = ch as u32;
            if (0x20..=0x7E).contains(&u) {
                let idx = (u - 0x20) as usize;
                if let Some(g) = fc.ascii_1x[idx] {
                    return g;
                }
                let leaked: &'static RasterGlyph = Box::leak(Box::new(build_raster_glyph(ch, s, 1.0)));
                fc.ascii_1x[idx] = Some(leaked);
                return leaked;
            }
        }
        if let Some(&g) = fc.other.get(&(ch, s, key_s)) {
            return g;
        }
        let eff_ui = key_s as f32 / 100.0;
        let leaked: &'static RasterGlyph = Box::leak(Box::new(build_raster_glyph(ch, s, eff_ui)));
        fc.other.insert((ch, s, key_s), leaked);
        leaked
    })
}

fn dist_seg_sq(px: f32, py: f32, x0: f32, y0: f32, x1: f32, y1: f32) -> f32 {
    let vx = x1 - x0;
    let vy = y1 - y0;
    let fx = px - x0;
    let fy = py - y0;
    let len2 = vx * vx + vy * vy;
    if len2 <= 0.0001 {
        return fx * fx + fy * fy;
    }
    let t = ((fx * vx + fy * vy) / len2).clamp(0.0, 1.0);
    let dx = fx - vx * t;
    let dy = fy - vy * t;
    dx * dx + dy * dy
}

fn flatten_segs(segs: &[Seg], scale_f: f32, lines: &mut Vec<(f32, f32, f32, f32)>, dots: &mut Vec<(f32, f32, f32)>) {
    let s = scale_f;
    for &seg in segs {
        match seg {
            Seg::L(x0, y0, x1, y1) => {
                lines.push((x0 as f32 * s, y0 as f32 * s, x1 as f32 * s, y1 as f32 * s));
            }
            Seg::Q(x0, y0, cx, cy, x1, y1) => {
                let steps = 10usize;
                let mut px = x0 as f32 * s;
                let mut py = y0 as f32 * s;
                for i in 1..=steps {
                    let t = i as f32 / steps as f32;
                    let mt = 1.0 - t;
                    let nx = (mt * mt * (x0 as f32) + 2.0 * mt * t * (cx as f32) + t * t * (x1 as f32)) * s;
                    let ny = (mt * mt * (y0 as f32) + 2.0 * mt * t * (cy as f32) + t * t * (y1 as f32)) * s;
                    lines.push((px, py, nx, ny));
                    px = nx;
                    py = ny;
                }
            }
            Seg::E(cx, cy, rx, ry, a0, a1) => {
                let span = (a1 - a0).abs();
                let steps = ((span / 18).max(6)) as usize;
                let deg2rad = std::f32::consts::PI / 180.0;
                let mut prev_x = (cx as f32 + (rx as f32) * (a0 as f32 * deg2rad).cos()) * s;
                let mut prev_y = (cy as f32 + (ry as f32) * (a0 as f32 * deg2rad).sin()) * s;
                for i in 1..=steps {
                    let ang = (a0 as f32 + ((a1 - a0) as f32) * (i as f32 / steps as f32)) * deg2rad;
                    let nx = (cx as f32 + (rx as f32) * ang.cos()) * s;
                    let ny = (cy as f32 + (ry as f32) * ang.sin()) * s;
                    lines.push((prev_x, prev_y, nx, ny));
                    prev_x = nx;
                    prev_y = ny;
                }
            }
            Seg::D(cx, cy, r) => {
                dots.push((cx as f32 * s, cy as f32 * s, (r as f32 * s).max(0.75)));
            }
        }
    }
}

fn build_raster_glyph(ch: char, scale: i32, ui_scale: f32) -> RasterGlyph {
    let vg = vector_glyph(ch);
    let base_h = px_height_for_scale(scale) as f32;
    let px_h = (base_h * ui_scale).round().clamp(10.0, 128.0) as i32;
    let unit = (px_h as f32) / 100.0;
    let advance_f = ((vg.advance as f32) * unit).max(3.0);
    let advance = advance_f.round() as i32;
    let width = (advance_f.ceil() as usize + 3).max(4);
    let height = px_h as usize;

    if vg.segs.is_empty() {
        return RasterGlyph {
            advance,
            advance_f,
            width,
            height,
            alpha: vec![0; width * height],
        };
    }

    let mut lines = Vec::with_capacity(24);
    let mut dots = Vec::with_capacity(4);
    flatten_segs(vg.segs, unit, &mut lines, &mut dots);

    let stroke_r = (0.56 * (px_h as f32 / 14.0).powf(0.88)).clamp(0.50, 2.6);
    let aa_feather = (0.46 * (14.0 / (px_h as f32)).sqrt()).clamp(0.32, 0.50);
    let mut alpha = vec![0u8; width * height];
    const SUB_OFF: [f32; 2] = [0.25, 0.75];

    for py in 0..height {
        for px in 0..width {
            let mut cov_sum = 0.0f32;
            for &oy in &SUB_OFF {
                let fy = py as f32 + oy;
                for &ox in &SUB_OFF {
                    let fx = px as f32 + ox;
                    let mut min_dist = f32::MAX;
                    for &(x0, y0, x1, y1) in &lines {
                        let d2 = dist_seg_sq(fx, fy, x0, y0, x1, y1);
                        let d = d2.sqrt() - stroke_r;
                        if d < min_dist {
                            min_dist = d;
                        }
                    }
                    for &(cx, cy, dr) in &dots {
                        let d = ((fx - cx) * (fx - cx) + (fy - cy) * (fy - cy)).sqrt() - dr;
                        if d < min_dist {
                            min_dist = d;
                        }
                    }
                    cov_sum += ((aa_feather - min_dist) / (aa_feather * 2.0)).clamp(0.0, 1.0);
                }
            }
            let cov = (cov_sum * 0.25).clamp(0.0, 1.0);
            if cov > 0.015 {
                // Perceptual gamma lift so diagonal & subpixel-aligned stems don't wash out
                let lifted = cov.powf(0.74);
                alpha[py * width + px] = (lifted * 255.0).round().clamp(0.0, 255.0) as u8;
            }
        }
    }

    RasterGlyph {
        advance,
        advance_f,
        width,
        height,
        alpha,
    }
}

