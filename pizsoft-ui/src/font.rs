pub const GLYPH_H: usize = 12;

#[derive(Clone, Copy)]
pub struct Glyph {
    pub width: u8,
    pub rows: [u8; GLYPH_H],
}

impl Glyph {
    const fn new(width: u8, rows: [u8; GLYPH_H]) -> Self {
        Self { width, rows }
    }
}

pub fn measure_text(s: &str, scale: i32) -> i32 {
    let sc = scale.max(1);
    let mut w = 0i32;
    for ch in s.chars() {
        w += (glyph(ch).width as i32) * sc;
    }
    w
}

